"""Prosody feature extraction on synthetic audio, and the transcribe / answer endpoints.

Synthetic "speech" is a harmonic tone (a rough stand-in for a voiced sound) in bursts separated by silence, so the
expected pauses, latency and pitch are known exactly.
"""
import io
import sys
from pathlib import Path

import numpy as np
import pytest
import soundfile as sf

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import prosody  # noqa: E402

SR = 16000


def tone(dur, f0=180.0, amp=0.3, vibrato=0.0):
    t = np.arange(int(dur * SR)) / SR
    f = f0 * (1 + vibrato * np.sin(2 * np.pi * 4 * t))
    phase = 2 * np.pi * np.cumsum(f) / SR
    y = sum(np.sin(h * phase) / h for h in (1, 2, 3, 4))
    y = y / np.max(np.abs(y)) * amp
    fade = int(0.01 * SR)
    y[:fade] *= np.linspace(0, 1, fade)
    y[-fade:] *= np.linspace(1, 0, fade)
    return y.astype(np.float32)


def silence(dur):
    return np.zeros(int(dur * SR), dtype=np.float32)


def clip(parts):
    return np.concatenate(parts)


def test_latency_and_duration():
    w = clip([silence(1.2), tone(1.5), silence(0.3)])
    f = prosody.extract(w)
    assert abs(f["duration_s"] - 3.0) < 0.01
    assert abs(f["latency_s"] - 1.2) < 0.08
    assert abs(f["speech_s"] - 1.5) < 0.1


def test_long_pauses_are_detected_and_measured():
    w = clip([tone(1.0), silence(0.9), tone(1.0), silence(0.9), tone(1.0)])
    f = prosody.extract(w)
    assert f["n_pauses"] == 2
    assert 0.75 < f["pause_mean_s"] < 1.05
    assert 0.3 < f["pause_ratio"] < 0.5


def test_short_gaps_are_not_pauses_and_pause_ratio_orders_correctly():
    flowing = clip([tone(0.8), silence(0.1), tone(0.8), silence(0.1), tone(0.8)])
    halting = clip([tone(0.8), silence(0.8), tone(0.8), silence(0.8), tone(0.8)])
    a, b = prosody.extract(flowing), prosody.extract(halting)
    assert a["n_pauses"] == 0 and a["pause_ratio"] == 0
    assert b["pause_ratio"] > a["pause_ratio"] + 0.3


def test_speech_rate_fast_vs_slow_from_word_timings():
    def words(n, dur):
        return [{"word": f"w{i}", "start": i * dur / n, "end": (i + 0.8) * dur / n} for i in range(n)]
    w = clip([tone(4.0)])
    fast = prosody.extract(w, words(16, 4.0))["speech_rate_wps"]
    slow = prosody.extract(w, words(6, 4.0))["speech_rate_wps"]
    assert fast > slow * 2
    assert 3.0 < fast < 5.0
    assert prosody.extract(w)["speech_rate_wps"] is None


def test_pitch_mean_and_variability():
    flat = prosody.extract(tone(2.0, f0=180.0, vibrato=0.0))
    lively = prosody.extract(tone(2.0, f0=180.0, vibrato=0.08))
    assert flat["pitch_mean_hz"] is not None and abs(flat["pitch_mean_hz"] - 180) < 12
    assert lively["pitch_std_st"] > flat["pitch_std_st"] + 0.3
    low = prosody.extract(tone(2.0, f0=110.0))
    assert low["pitch_mean_hz"] < flat["pitch_mean_hz"] - 40


def test_energy_loud_vs_quiet():
    loud = prosody.extract(tone(1.5, amp=0.5))
    quiet = prosody.extract(tone(1.5, amp=0.05))
    assert loud["energy_mean_db"] > quiet["energy_mean_db"] + 10


def test_silent_or_too_short_input_returns_nones_not_errors():
    for w in (silence(2.0), tone(0.1)):
        f = prosody.extract(w)
        assert f["latency_s"] is None and f["pause_ratio"] is None and f["pitch_mean_hz"] is None


def test_resamples_other_rates():
    w = clip([silence(0.5), tone(1.0)])
    import librosa
    w8 = librosa.resample(w, orig_sr=SR, target_sr=8000)
    f = prosody.extract(w8, sr=8000)
    assert abs(f["latency_s"] - 0.5) < 0.1


@pytest.fixture(scope="module")
def client():
    import main
    from fastapi.testclient import TestClient
    with TestClient(main.app) as c:
        yield c


def _wav(w):
    buf = io.BytesIO()
    sf.write(buf, w, SR, format="WAV")
    return buf.getvalue()


def test_prosody_endpoint(client):
    w = clip([silence(0.6), tone(1.0), silence(0.6), tone(1.0)])
    r = client.post("/analyse/prosody", files={"file": ("a.wav", _wav(w), "audio/wav")})
    assert r.status_code == 200
    body = r.json()
    assert abs(body["latency_s"] - 0.6) < 0.1
    assert body["n_pauses"] == 1


def test_transcribe_returns_empty_text_for_silence(client):
    r = client.post("/transcribe", files={"file": ("a.wav", _wav(silence(1.5)), "audio/wav")})
    assert r.status_code == 200
    assert r.json()["text"] == ""


def test_transcribe_real_speech_if_a_sample_exists(client):
    sample = HERE / "sample_speech.wav"
    if not sample.exists():
        pytest.skip("no sample_speech.wav (generated by app/scripts/make_speech_sample.ps1)")
    r = client.post("/transcribe", files={"file": ("s.wav", sample.read_bytes(), "audio/wav")})
    body = r.json()
    assert "tired" in body["text"].lower() or "sleep" in body["text"].lower()
    assert body["words"] and body["words"][0]["start"] >= 0


def test_analyse_answer_combines_everything(client):
    w = clip([silence(0.5), tone(1.2)])
    r = client.post("/analyse/answer", files={"file": ("a.wav", _wav(w), "audio/wav")})
    assert r.status_code == 200
    body = r.json()
    assert set(body) == {"transcript", "prosody", "voice_emotion"}
    assert abs(body["prosody"]["latency_s"] - 0.5) < 0.1
    if body["voice_emotion"]:
        assert abs(sum(body["voice_emotion"]["probabilities"].values()) - 1) < 1e-3
